function busur(cx: number, cy: number, rx: number, ry: number, d0: number, d1: number, n = 14): Guratan {
	const g: Guratan = [];
	for (let i = 0; i <= n; i++) {
		const a = ((d0 + ((d1 - d0) * i) / n) * Math.PI) / 180;
		g.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)]);
	}
	return g;
}

